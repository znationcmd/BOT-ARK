test('role IDs are validated and unchanged configuration preserved',async()=>{
 const old={channelId:CHANNEL,roleIds:[NEW,NEW],joinNotifyRoleId:ALERT_JOIN,leaveNotifyRoleId:ALERT_LEAVE,joinMessage:'Bonjour {user}',leaveMessage:'Au revoir {user}'};
 const created=await modules.save(G,'welcome',{enabled:true,config:old});
 assert.deepEqual(created.config.roleIds,[NEW]);
 const edited=await modules.save(G,'welcome',{config:{channelId:CHANNEL}});
 assert.deepEqual(edited.config.roleIds,[NEW]);
 assert.equal(edited.config.leaveNotifyRoleId,ALERT_LEAVE);
 await assert.rejects(modules.save(G,'welcome',{config:{roleIds:['bad-role']}}),e=>e.code==='invalidInput');
 await assert.rejects(modules.save(G,'welcome',{config:{joinNotifyRoleId:'not-an-id'}}),e=>e.code==='invalidInput');
 await assert.rejects(modules.save(G,'welcome',{config:{roleIds:Array.from({length:21},(_,i)=>String(40000000000000000+i))}}),e=>e.code==='invalidInput');
});
test('join assigns only permitted nonprivileged roles and pings join alert; leave pings separate alert without granting',async()=>{
 const sent=[],granted=[];
 const valid={id:NEW,name:'Survivant',position:5,managed:false,permissions:{has:()=>false}};
 const privileged={id:'40000000000001004',name:'Admin',position:4,managed:false,permissions:{has:p=>String(p)==='Administrator'}};
 const tooHigh={id:'40000000000001005',name:'Higher',position:55,managed:false,permissions:{has:()=>false}};
 const joinedRole={id:ALERT_JOIN,managed:false};
 const leftRole={id:ALERT_LEAVE,managed:false};
 const roles=new Map([valid,privileged,tooHigh,joinedRole,leftRole].map(r=>[r.id,r]));
 const guild={id:G,name:'CMD ARK',roles:{cache:roles},members:{fetchMe:async()=>({permissions:{has:p=>p==='ManageRoles'},roles:{highest:{position:50}}})},channels:{fetch:async id=>id===CHANNEL?{id, isTextBased:()=>true,send:async obj=>{sent.push(obj);return {id:'90000000000000001'}}}:null}};
 const client={guilds:{fetch:async id=>id===G?guild:null}};
 const member={id:USER,guild,toString:()=>'<@'+USER+'>',roles:{add:async role=>granted.push(role.id)},user:{tag:'somebody'}};
 await modules.save(G,'welcome',{config:{roleIds:[NEW,privileged.id,tooHigh.id],joinNotifyRoleId:ALERT_JOIN,leaveNotifyRoleId:ALERT_LEAVE}});
 await modules.handleJoin(client,member);
 assert.deepEqual(granted,[NEW]);
 assert.equal(sent.length,1);
 assert.ok(sent[0].content.startsWith('<@&'+ALERT_JOIN+'>'));
 assert.deepEqual(sent[0].allowedMentions.roles,[ALERT_JOIN]);
 await modules.handleLeave(client,member);
 assert.equal(sent.length,2);
 assert.ok(sent[1].content.startsWith('<@&'+ALERT_LEAVE+'>'));
 assert.deepEqual(sent[1].allowedMentions.roles,[ALERT_LEAVE]);
 assert.deepEqual(granted,[NEW]);
});
